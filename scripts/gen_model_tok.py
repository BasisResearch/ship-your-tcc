#!/usr/bin/env python3
"""Generate Tcc/Model/Tok.lean: tcc's token numbers and keyword table.

F3 (DESIGN-COMPILER.md §4.1): the executable Lean model of tcc numbers its
tokens exactly as tcc does. tcc's `enum tcc_token` is `TOK_LAST = 255`
followed by one entry per DEF(id, str) of tcctok.h (with riscv64-tok.h, the
assembler's tokens), as configured for the image: TCC_TARGET_RISCV64,
PTR_SIZE 8, CONFIG_TCC_ASM, no CONFIG_TCC_BCHECK (c/src/tcc-config/config.h).
`tcc_keywords` is the concatenation of the strings in the same order;
tccpp_new allocates them as the first identifiers (tok_ident = 256, ...).

The DEFs are expanded by the host C preprocessor on the patched source
(build/tcc-src, scripts/tcc_src.sh), so the generator follows the header.

    scripts/gen_model_tok.py [--check]
"""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'build', 'tcc-src')
OUT = os.path.join(ROOT, 'Tcc', 'Model', 'Tok.lean')


def tokens():
    subprocess.run([os.path.join(ROOT, 'scripts', 'tcc_src.sh'), SRC], check=True)
    stub = ('#define TCC_TARGET_RISCV64 1\n#define PTR_SIZE 8\n#define CONFIG_TCC_ASM 1\n'
            '#define DEF(id, str) @TOK id str @END\n#include "tcctok.h"\n')
    with tempfile.NamedTemporaryFile('w', suffix='.c', delete=False) as f:
        f.write(stub)
        name = f.name
    try:
        out = subprocess.run(['gcc', '-E', '-P', '-I', SRC, name], check=True,
                             capture_output=True, text=True).stdout
    finally:
        os.unlink(name)
    toks = []
    for m in re.finditer(r'@TOK\s+(\w+)\s+(.*?)\s*@END', out, re.S):
        ident, s = m.group(1), m.group(2)
        # adjacent string literals, as C concatenates them
        parts = re.findall(r'"((?:[^"\\]|\\.)*)"', s)
        toks.append((ident, ''.join(parts)))
    return toks


def lean_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render(toks):
    lines = [
        '/-! GENERATED by scripts/gen_model_tok.py from tcc\'s tcctok.h (with',
        '    riscv64-tok.h) as configured for the image. Do not edit.',
        '',
        '    tcc\'s token numbers: `TOK_LAST = 255`, then one per `DEF`; and',
        '    `tcc_keywords`, the identifier strings tccpp_new allocates first. -/',
        '',
        'namespace Tcc.Model.Tok',
        '',
    ]
    seen = set()
    for i, (ident, s) in enumerate(toks):
        if ident in seen:
            continue
        seen.add(ident)
        lines.append(f'@[inline] def {ident} : Int32 := {256 + i}')
    lines.append('')
    lines.append(f'/-- the number of DEF tokens (tok_ident after tccpp_new\'s keywords is 256 + this) -/')
    lines.append(f'def nbKeywords : Nat := {len(toks)}')
    lines.append('')
    lines.append('/-- tcc_keywords, in token order -/')
    lines.append('def keywords : Array String := #[')
    for i, (ident, s) in enumerate(toks):
        sep = ',' if i + 1 < len(toks) else ''
        lines.append(f'  {lean_str(s)}{sep}')
    lines.append(']')
    lines.append('')
    lines.append('end Tcc.Model.Tok')
    lines.append('')
    return '\n'.join(lines)


def main():
    text = render(tokens())
    if '--check' in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        if old != text:
            print(f'{OUT} is stale: rerun scripts/gen_model_tok.py', file=sys.stderr)
            sys.exit(1)
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write(text)


if __name__ == '__main__':
    main()
