#!/usr/bin/env python3
"""Bounded ISA probes against the unmodified sister-project Sail executable.

These are platform diagnostics, not tcc -run results or kernel proofs.
Each probe enables misa bits A/C/D/F/I/M and mstatus.FS before the instruction.
The trap handler preserves mcause/mepc/mtval in a2/a3/a4, then exits over HTIF.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
TOOLCHAIN = Path.home() / "toolchains/xpack-riscv-none-elf-gcc-15.2.0-1"
DEFAULT_EMU = ROOT.parent / "ship-your-ocaml/riscv-lean/lean_emulator/.lake/build/bin/lean_riscv_emulator"
PROBES = {
    "integer": ("add a0, a0, a1", 13),
    "compressed": (".2byte 0x0001", 6),  # c.nop
    "multiply": ("mul a0, a0, a1", 42),
    "divide": ("div a0, a0, a1", 0),
    "atomic": ("la t1, scratch\n    amoadd.d a0, a1, (t1)", 0),
    "float": ("fcvt.s.w fa0, a0\n    fcvt.w.s a0, fa0, rtz", 6),
    "double": ("fcvt.d.w fa0, a0\n    fcvt.w.d a0, fa0, rtz", 6),
    "fence_i": ("fence.i", 6),
}

TEMPLATE = """/* Generated by scripts/probe_sail.py. */
.option norvc
.section .text.init
.globl _start
_start:
    la sp, __stack_top
    la t0, trap
    csrw mtvec, t0
    li t0, 0x112d
    csrs misa, t0
    li t0, 0x6000
    csrs mstatus, t0
    csrr s4, misa
    csrr s5, mstatus
    li a0, 6
    li a1, 7
.globl probe_instruction
probe_instruction:
    INSTRUCTION
    li t0, EXPECTED
    bne a0, t0, bad_result
    li a0, 1
    j finish
bad_result:
    li a0, 3
    j finish
.balign 4
trap:
    csrr a2, mcause
    csrr a3, mepc
    csrr a4, mtval
    li a0, 133 /* HTIF exit 66: unexpected instruction trap */
.globl probe_trap_report
probe_trap_report:
    j finish
finish:
    la t0, tohost
.globl probe_exit
probe_exit:
    sd a0, 0(t0)
1:  j 1b
.section .data
.balign 8
scratch: .dword 0
.section .tohost,"aw",@progbits
.balign 64
.globl tohost
tohost: .dword 0
.globl fromhost
fromhost: .dword 0
"""


def run(cmd):
    return subprocess.run([str(x) for x in cmd], capture_output=True, text=True,
                          timeout=30)


def digest(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--emu", type=Path, default=DEFAULT_EMU)
    ap.add_argument("--toolchain", type=Path, default=TOOLCHAIN)
    args = ap.parse_args()
    build = ROOT / "build/probes"
    results = ROOT / "results/probes"
    build.mkdir(parents=True, exist_ok=True)
    results.mkdir(parents=True, exist_ok=True)
    prefix = args.toolchain / "bin/riscv-none-elf-"
    cc, nm, objdump = (str(prefix) + x for x in ("gcc", "nm", "objdump"))
    report = {"emulator": str(args.emu.resolve()),
              "emulator_sha256": digest(args.emu),
              "gcc_version": run([cc, "--version"]).stdout.splitlines()[0],
              "max_steps_per_probe": 200, "probes": []}
    for name, (instruction, expected) in PROBES.items():
        source = build / (name + ".S")
        elf = build / (name + ".elf")
        source.write_text(TEMPLATE.replace("INSTRUCTION", instruction)
                          .replace("EXPECTED", str(expected)))
        compile_result = run([cc, "-march=rv64gc", "-mabi=lp64d", "-nostdlib",
                              "-T", ROOT / "c/src/link.ld", source, "-o", elf])
        (results / (name + ".build.log")).write_text(compile_result.stderr)
        compile_result.check_returncode()
        syms = {p[2]: int(p[0], 16) for line in run([nm, elf]).stdout.splitlines()
                if len(p := line.split()) == 3}
        disasm = run([objdump, "-d", elf])
        disasm.check_returncode()
        (results / (name + ".disasm")).write_text(disasm.stdout)
        result = run([args.emu, elf, "--trace-all", "--max-steps", 200])
        (results / (name + ".stdout")).write_text(result.stdout)
        (results / (name + ".trace")).write_text(result.stderr)
        rows = [line.split("\t") for line in result.stderr.splitlines()
                if line.startswith("T\t")]
        exit_row = next((r for r in rows if int(r[2], 16) == syms["probe_exit"]), None)
        trap_row = next((r for r in rows if int(r[2], 16) == syms["probe_trap_report"]), None)
        probe_row = next((r for r in rows if int(r[2], 16) == syms["probe_instruction"]), None)
        # Trace fields 4..34 are x1..x31 AFTER the instruction.
        record = {
            "name": name, "instruction": instruction,
            "elf_sha256": digest(elf), "exit": result.returncode,
            "fuel_out": "TRACE-FUEL-OUT" in result.stderr,
            "steps": int(exit_row[1]) + 1 if exit_row else None,
            "instruction_pc": hex(syms["probe_instruction"]),
            "instruction_step": int(probe_row[1]) if probe_row else None,
            "misa": hex(int(probe_row[23], 16)) if probe_row else None,
            "mstatus": hex(int(probe_row[24], 16)) if probe_row else None,
            "mcause": int(trap_row[15], 16) if trap_row else None,
            "mepc": hex(int(trap_row[16], 16)) if trap_row else None,
            "mtval": hex(int(trap_row[17], 16)) if trap_row else None,
            "passed": result.returncode == 0 and exit_row is not None and trap_row is None,
        }
        if exit_row is None or record["fuel_out"]:
            raise RuntimeError(f"{name}: probe failed to reach HTIF exit")
        report["probes"].append(record)
        print(json.dumps(record))
    (ROOT / "results/isa-probes.json").write_text(json.dumps(report, indent=2) + "\n")


if __name__ == "__main__":
    main()
