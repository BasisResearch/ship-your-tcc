#!/usr/bin/env python3
"""Derive the no-libc, active-member observation of the existing C11 union test.
The original test also reads inactive union tails; those bytes are unspecified
in CSem. Retain the original verbatim for the separate residual run.
"""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--check', action='store_true')
a = p.parse_args()
s = (ROOT/'c/tests/c11/union.c').read_text()
assert 'bad |= h.a!=12 || h.s.z || enclosing.a!=12 || enclosing.s.z;' in s
s = s.replace('#include <stdio.h>\n', '')
s = s.replace('bad |= h.a!=12 || h.s.z || enclosing.a!=12 || enclosing.s.z;',
              'bad |= h.a!=12 || enclosing.a!=12;')
s = s.replace('  printf("union %d\\n", bad);\n', '')
s = '/* Generated by scripts/gen_union_c11_observation.py from c/tests/c11/union.c. */\n'+s
out = ROOT/'csem/tests/union-init/c11-active-members.c'
if a.check:
    assert out.read_text() == s, 'stale C11 union observation fixture'
else:
    out.write_text(s)
