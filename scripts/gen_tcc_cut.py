#!/usr/bin/env python3
"""Generate the Lean side of a captured cut (PHASES 3a) from scripts/tcc_cut.py.

    scripts/gen_tcc_cut.py --capture build/p3/sum-cut [--elf build/p3/sum.elf]
    scripts/gen_tcc_cut.py --check

--capture reads tcc_cut.py's output, writes the committed input
results/p3/sum-cut.json (the cut's metadata, the view's bytes, the compile
phase's read ranges) and the Lean files. --check regenerates the Lean files
from results/p3/sum-cut.json and fails on any difference; the ELF-data files
(Tcc/Capture/Sum/Elf*.lean) are regenerated from the ELF, so they are checked
only when an ELF with the pinned SHA-256 is at --elf (else reported skipped).

Lean files (GENERATED headers; never edit them, change this script):
* Tcc/Capture/Sum/Regs.lean: the cut's PC, step number and GPRs;
* Tcc/Capture/Sum/View.lean: the view as packed chunks, host chunks (bytes
  of the ELF's loaded image) apart from observed chunks (bytes the compile
  phase stored: the generated code, tcc's relocated libc members, data);
* Tcc/Capture/Sum/Elf.lean + Elf/P<k>.lean: `elfImage`, the ELF's loaded
  bytes that `TccSumElf` pins (every byte the compile phase reads before
  writing it, and the view's host bytes), read from the ELF file; zero runs
  are chunks with `packed = 0`;
* Tcc/Capture/Sum/Witness.lean: `cut`, `cut_ok`, the per-chunk kernel checks
  that the view's host bytes are the ELF's (`host<i>_elf`).
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / 'results/p3/sum-cut.json'
OUT = ROOT / 'Tcc/Capture/Sum'
ELF = ROOT / 'build/p3/sum.elf'
NS = 'Tcc.Capture.Sum'
RUNTIME_SHA = '9e1142dc96d8db10'  # scripts/tcc_cut.py; c/tests/run.sh runtime_sha
CHUNK = 256          # bytes per data chunk
ZERO_RUN = 32        # zero runs at least this long become `packed = 0` chunks
PART = 128           # chunks per elfImage part definition
PARTS_PER_FILE = 8


def runs_of(pairs):
    """[(addr, byte)] sorted -> [[base, bytes]] maximal contiguous runs."""
    out = []
    for a, b in pairs:
        if out and out[-1][0] + len(out[-1][1]) == a:
            out[-1][1].append(b)
        else:
            out.append([a, [b]])
    return out


def ranges_of(addrs):
    out = []
    for a in addrs:
        if out and out[-1][0] + out[-1][1] == a:
            out[-1][1] += 1
        else:
            out.append([a, 1])
    return out


def chunks_of(base, bs, zero_runs=False):
    """Split a run into chunks (base, len, packed): with zero_runs, maximal
    runs of at least ZERO_RUN zeros are single `packed = 0` chunks; other
    spans are cut into chunks of at most CHUNK bytes."""
    spans = []  # (start, end, is_zero_run)
    i, n = 0, len(bs)
    start = 0
    while i < n:
        if zero_runs and bs[i] == 0:
            j = i
            while j < n and bs[j] == 0:
                j += 1
            if j - i >= ZERO_RUN:
                if start < i:
                    spans.append((start, i, False))
                spans.append((i, j, True))
                start = j
            i = j
        else:
            i += 1
    if start < n:
        spans.append((start, n, False))
    out = []
    for s0, s1, z in spans:
        if z:
            out.append((base + s0, s1 - s0, 0))
            continue
        for c in range(s0, s1, CHUNK):
            e = min(c + CHUNK, s1)
            out.append((base + c, e - c, int.from_bytes(bytes(bs[c:e]), 'little')))
    return out


def chunk_lit(c):
    base, ln, packed = c
    return f'⟨0x{base:x}, {ln}, 0x{packed:x}⟩'


def header(what, extra=''):
    return (f'/-! GENERATED by scripts/gen_tcc_cut.py from results/p3/sum-cut.json '
            f'(scripts/tcc_cut.py){extra}. Do not edit: change the generator.\n\n{what} -/\n')


# --- ELF ----------------------------------------------------------------------

def elf_segments(data):
    assert data[:4] == b'\x7fELF' and data[4] == 2 and data[5] == 1
    phoff, = struct.unpack_from('<Q', data, 0x20)
    phentsize, phnum = struct.unpack_from('<HH', data, 0x36)
    segs = []
    for i in range(phnum):
        (_t, _f, off, vaddr, _p, filesz, _m, _a) = struct.unpack_from('<IIQQQQQQ', data, phoff + i * phentsize)
        if filesz:
            segs.append((vaddr, data[off:off + filesz]))
    return segs


def elf_byte(segs, a):
    for base, body in segs:
        if base <= a < base + len(body):
            return body[a - base]
    return None


# --- capture → committed input ---------------------------------------------------

def capture(cutdir, elf):
    meta = json.loads((cutdir / 'cut.json').read_text())
    if meta['runtime_sha'] != RUNTIME_SHA:
        sys.exit('gen_tcc_cut: runtime sha differs from the pinned one')
    data = elf.read_bytes()
    if hashlib.sha256(data).hexdigest() != meta['elf_sha256']:
        sys.exit('gen_tcc_cut: --elf is not the captured ELF')
    segs = elf_segments(data)
    view = []
    for line in (cutdir / 'view.tsv').read_text().splitlines():
        if line.startswith('#'):
            continue
        a, b, src = line.split('\t')
        a, b = int(a, 16), int(b, 16)
        if src == 'elf' and elf_byte(segs, a) != b:
            sys.exit(f'gen_tcc_cut: view byte {a:#x} is not the ELF byte')
        view.append((a, b, src))
    reads = []
    for line in (cutdir / 'compile_reads.tsv').read_text().splitlines():
        if not line.startswith('#'):
            reads.append(int(line.split('\t')[0], 16))
    runs = []
    for src in ('elf', 'store'):
        for base, bs in runs_of([(a, b) for a, b, s in view if s == src]):
            runs.append([f'{base:x}', bytes(bs).hex(), src])
    inp = {k: meta[k] for k in ('elf_sha256', 'runtime_sha', 'enter', 'tohost', 'exit_store',
                                'cut_step', 'end_step', 'program_steps', 'regs', 'console',
                                'compile_written_bytes', 'compile_reads_bytes')}
    inp['entry'] = struct.unpack_from('<Q', data, 0x18)[0]
    inp['view'] = runs
    inp['compile_reads'] = [[f'{a:x}', n] for a, n in ranges_of(reads)]
    INPUT.parent.mkdir(parents=True, exist_ok=True)
    INPUT.write_text(json.dumps(inp, indent=0) + '\n')
    return inp


# --- Lean emitters -------------------------------------------------------------------

def gen_regs(inp):
    regs = inp['regs']
    arms = '\n'.join(f'  | {i + 1} => 0x{v:x}#64' for i, v in enumerate(regs))
    return f'''import Tcc.Boot.Regs

{header("The registers at the cut of `tcc -run /prog.c` for P = `c/tests/p3/sum.c`: the first step at `tcc_baremetal_enter` (the jump into the generated code) of the FLAGS=0 image, observed on the emulator. Observations, no execution claim: that the machine reaches them is `CompileCut_Statement`.", f"; ELF sha256 {inp['elf_sha256']}, runtime sha {inp['runtime_sha']}")}
namespace {NS}

/-- `tcc_baremetal_enter`: `mv`s then `jr a5` into the generated code. -/
def enterPc : BitVec 64 := 0x{inp['enter']:x}#64

/-- Steps from reset to the cut (tcc's compile phase). -/
def cutStep : Nat := {inp['cut_step']}

/-- Steps from the cut to `_exit`'s `tohost` store, inclusive. -/
def programSteps : Nat := {inp['program_steps']}

/-- The image's entry point (`_start`) and `.tohost` address. -/
def entryAddr : Nat := 0x{inp['entry']:x}
def tohostAddr : Nat := 0x{inp['tohost']:x}

/-- The copied machine layer's mailbox address is this image's. -/
theorem tohostAddr_eq : Vsa.Sim.tohostAddr = tohostAddr := rfl

/-- `x1 … x31` at the cut. -/
def regs : Nat → BitVec 64
{arms}
  | _ => 0#64

end {NS}
'''


def view_chunks(inp):
    host, obs = [], []
    for base, hx, src in inp['view']:
        cs = chunks_of(int(base, 16), list(bytes.fromhex(hx)))
        (host if src == 'elf' else obs).extend(cs)
    return host, obs


def gen_view(inp):
    host, obs = view_chunks(inp)
    nbytes = sum(c[1] for c in host + obs)
    hdefs = '\n'.join(f'def hostChunk{i} : Chunk := {chunk_lit(c)}' for i, c in enumerate(host))
    hlist = ', '.join(f'hostChunk{i}' for i in range(len(host)))
    olist = ',\n   '.join(chunk_lit(c) for c in obs)
    return f'''import Tcc.Boot.View

{header(f"The view of the cut: the {nbytes} bytes the program phase ({inp['program_steps']} steps) fetches or loads before it writes them, with their values at the cut, as packed chunks. Host chunks are bytes of the ELF's loaded image (`Witness.host<i>_elf` checks each against `elfImage`). Observed chunks are bytes tcc's compile phase stored (the generated code at the arena's start, the libc/libgcc members tcc relocated into the arena, the format string, `.data`/`.bss` words): observations of the emulator, which `CompileCut_Statement` claims.")}
namespace {NS}

open Tcc.Boot

{hdefs}

/-- Bytes of the ELF's loaded image ({sum(c[1] for c in host)} bytes). -/
def hostChunks : List Chunk := [{hlist}]

/-- Bytes the compile phase stored ({sum(c[1] for c in obs)} bytes). -/
def obsChunks : List Chunk :=
  [{olist}]

def viewChunks : List Chunk := hostChunks ++ obsChunks

/-- The cut's view. -/
def view : Nat → Option (BitVec 8) := chunkView viewChunks

end {NS}
'''


def elf_chunks(inp, segs):
    addrs = set()
    for base, n in inp['compile_reads']:
        b = int(base, 16)
        addrs.update(range(b, b + n))
    for base, hx, src in inp['view']:
        if src == 'elf':
            b = int(base, 16)
            addrs.update(range(b, b + len(hx) // 2))
    present, absent = [], []
    for a in sorted(addrs):
        v = elf_byte(segs, a)
        if v is None:
            absent.append(a)
        else:
            present.append((a, v))
    chunks = []
    for base, bs in runs_of(present):
        chunks += chunks_of(base, bs, zero_runs=True)
    return chunks, ranges_of(absent)


def gen_elf(inp, segs):
    chunks, absent = elf_chunks(inp, segs)
    parts = [chunks[i:i + PART] for i in range(0, len(chunks), PART)]
    files = {}
    nfiles = (len(parts) + PARTS_PER_FILE - 1) // PARTS_PER_FILE
    for f in range(nfiles):
        body = []
        for p in range(f * PARTS_PER_FILE, min(len(parts), (f + 1) * PARTS_PER_FILE)):
            lits = ',\n   '.join(chunk_lit(c) for c in parts[p])
            body.append(f'def part{p} : List Chunk :=\n  [{lits}]\n')
        files[f'Elf/P{f}.lean'] = f'''import Tcc.Boot.View

{header("A slice of `elfImage`'s chunks (`Elf.lean`), read from the ELF file.")}
namespace {NS}.Elf

open Tcc.Boot

{chr(10).join(body)}
end {NS}.Elf
'''
    # balanced if-tree over the parts' lower bounds
    lows = [p[0][0] for p in parts]

    def tree(lo, hi, ind):
        if hi - lo == 1:
            return f'chunkView part{lo} k'
        mid = (lo + hi) // 2
        pad = ' ' * ind
        return (f'if k < 0x{lows[mid]:x} then\n{pad}  {tree(lo, mid, ind + 2)}\n'
                f'{pad}else\n{pad}  {tree(mid, hi, ind + 2)}')
    imports = '\n'.join(f'import {NS}.Elf.P{f}' for f in range(nfiles))
    nbytes = sum(c[1] for c in chunks)
    nz = sum(c[1] for c in chunks if c[2] == 0 and c[1] >= ZERO_RUN)
    absent_lits = ', '.join(f'(0x{a:x}, {n})' for a, n in absent)
    files['Elf.lean'] = f'''{imports}
import Tcc.Boot.Reset

{header(f"The ELF's loaded bytes that pin it (`TccSumElf`): every byte of the image's loaded memory (the emulator's `initializeMemory`) that the compile phase reads before writing it, and the view's host bytes: {nbytes} bytes ({nz} of them in zero runs) in {len(chunks)} chunks, read from the ELF file, never evaluated except by the host checks; and the {sum(n for _, n in absent)} bytes the compile phase reads that the ELF does not load (`elfAbsent`).", f"; ELF sha256 {inp['elf_sha256']}")}
namespace {NS}.Elf

open Tcc.Boot

/-- The pinned loaded bytes of the ELF. -/
def elfImage (k : Nat) : Option (BitVec 8) :=
  {tree(0, len(parts), 2)}

/-- Bytes the compile phase reads that the ELF does not load (they read as 0). -/
def elfAbsent : List (Nat × Nat) := [{absent_lits}]

end {NS}.Elf
'''
    return files


def gen_witness(inp):
    host, _ = view_chunks(inp)
    checks = '\n'.join(
        f'theorem host{i}_elf : hostChunk{i}.agrees Elf.elfImage = true := by decide +kernel'
        for i in range(len(host)))
    names = ', '.join(f'host{i}_elf' for i in range(len(host)))
    return f'''import Tcc.Capture.Sum.Regs
import Tcc.Capture.Sum.View
import Tcc.Capture.Sum.Elf
import Tcc.Boot.Cut

{header("The captured cut's representative configuration, its witness, and the kernel checks that the view's host bytes are the ELF's loaded bytes.")}
namespace {NS}

open Vsa.Machine Tcc.Boot

/-- The representative configuration: `cutState` over a memory holding
exactly the view, the captured GPRs, the captured step count. -/
def cut : Config := cutConfig regs enterPc viewChunks cutStep

theorem cut_captured : CapturedCut regs enterPc view cut :=
  cutConfig_captured regs enterPc viewChunks cutStep

/-! Each host chunk is the ELF's loaded bytes (one kernel `decide` each). -/

{checks}

theorem hostChunks_elf : ∀ c ∈ hostChunks, c.agrees Elf.elfImage = true := by
  simp only [hostChunks, List.mem_cons, List.not_mem_nil, or_false, forall_eq_or_imp, forall_eq]
  exact ⟨{names}⟩

/-- The view's host bytes are bytes of `elfImage`. -/
theorem hostView_elf : ∀ k b, chunkView hostChunks k = some b → Elf.elfImage k = some b :=
  chunkView_sub hostChunks_elf

end {NS}
'''


def render(inp, elf):
    files = {
        'Regs.lean': gen_regs(inp),
        'View.lean': gen_view(inp),
        'Witness.lean': gen_witness(inp),
    }
    elf_files = None
    if elf is not None and elf.exists():
        data = elf.read_bytes()
        if hashlib.sha256(data).hexdigest() == inp['elf_sha256']:
            elf_files = gen_elf(inp, elf_segments(data))
    return files, elf_files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--capture')
    ap.add_argument('--elf', default=str(ELF))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    elf = Path(a.elf)
    if a.capture:
        inp = capture(Path(a.capture), elf)
    else:
        inp = json.loads(INPUT.read_text())
    files, elf_files = render(inp, elf)
    if a.capture and elf_files is None:
        sys.exit('gen_tcc_cut: --capture needs the captured ELF')
    if elf_files:
        files.update(elf_files)
    if a.check:
        bad = [n for n, t in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != t]
        if bad:
            print('gen_tcc_cut: drift in ' + ', '.join(f'Tcc/Capture/Sum/{n}' for n in bad))
            sys.exit(1)
        print('gen_tcc_cut: up to date' + ('' if elf_files else
              f' (Elf*.lean skipped: no ELF with sha256 {inp["elf_sha256"][:16]}… at {elf})'))
        return
    for n, t in files.items():
        (OUT / n).parent.mkdir(parents=True, exist_ok=True)
        (OUT / n).write_text(t)
    print(f'gen_tcc_cut: wrote {len(files)} files')


if __name__ == '__main__':
    main()
