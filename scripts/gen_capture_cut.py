#!/usr/bin/env python3
"""Generate a native observation utility; no execution theorem is emitted.

Register enumeration and stepping are adapted from ship-your-ocaml
scripts/gen_boot_dump.py / boot_dump.lean, commit 7222d01e (ATTRIBUTION.md).
The executable imports the frozen Vsa.Elf API from ship-your-lua. Its
generated source and every build output belong to this repository.
"""
import argparse
import hashlib
from pathlib import Path
import re


BODY = r'''
structure CutState where
  state : CapturedState
  tick : Nat
  steps : Nat

def currentPC (s : CapturedState) : IO Nat := do
  let some pc := s.regs.get? .PC | throw (IO.userError "PC is undefined")
  return pc.toNat

-- Stop before the cut instruction. The step body is OCaml's bootdump loop,
-- calling the same frozen API as the machine relation, without changing Sail.
def observe (path : String) (target limit : Nat) : IO CutState := do
  let .ok (.elf64 elf) ← readElf path | throw (IO.userError "expected ELF64")
  let initial : CapturedState := ⟨{}, (), initializeMemory .B64 elf, (), 0, #[]⟩
  let .ok _ σ := (Vsa.setupElf elf).run initial | throw (IO.userError "setup failed")
  let mut c : CutState := ⟨σ, 0, 0⟩
  for _ in [:limit] do
    if (← currentPC c.state) == target then return c
    match (Vsa.stepOnce c.tick c.steps).run c.state with
    | .ok (.inr (tick, steps)) σ' => c := ⟨σ', tick, steps⟩
    | _ => throw (IO.userError s!"stopped before cut at {c.steps}")
  if (← currentPC c.state) == target then return c
  throw (IO.userError s!"cut not reached within {limit} steps")

def parseNat (s : String) : IO Nat := do
  let some n := s.toNat? | throw (IO.userError s!"expected decimal Nat: {s}")
  return n

def main (args : List String) : IO Unit := do
  let (elf, pcText, baseText, sizeText, outText, limitText) ← match args with
    | [elf, pc, base, size, out, limit] => pure (elf, pc, base, size, out, limit)
    | _ => throw (IO.userError "usage: capture_cut ELF PC ARENA_BASE ARENA_SIZE OUTDIR STEP_LIMIT (decimal numbers)")
  let target ← parseNat pcText
  let base ← parseNat baseText
  let size ← parseNat sizeText
  let limit ← parseNat limitText
  unless base == 0x86400000 && size == 0x400000 do
    throw (IO.userError "expected ship-your-tcc's 4 MiB arena")
  let c ← observe elf target limit
  -- FLAGS=0 is checked against ELF bytes by the host wrapper. Confirm that no
  -- compile/dump console output preceded the cut; never silently strip it.
  unless c.state.sailOutput.isEmpty do
    throw (IO.userError "console is not empty at the cut")
  let out : System.FilePath := outText
  let mut arena := ByteArray.empty
  -- One byte per address: 1 = present in the sparse map, 0 = absent.
  -- This intentionally avoids a packed-mask convention or a lost presence fact.
  let mut present := ByteArray.empty
  let mut count := 0
  for i in [:size] do
    match c.state.mem[base + i]? with
    | some b =>
      arena := arena.push b.toNat.toUInt8
      present := present.push 1
      count := count + 1
    | none =>
      arena := arena.push 0
      present := present.push 0
  IO.FS.writeBinFile (out / "arena.bin") arena
  IO.FS.writeBinFile (out / "arena.present.bin") present
  let mut rows := "-- Native observation only; startup reachability is open.\n"
  let mut defined := 0
  for r in allRegisters do
    let row := dumpRegister c.state r
    unless row.isEmpty do
      rows := rows ++ row ++ "\n"
      defined := defined + 1
  unless defined == c.state.regs.size do
    throw (IO.userError "register enumeration does not cover the complete map")
  IO.FS.writeFile (out / "registers.txt") rows
  IO.FS.writeFile (out / "console.txt") (String.join c.state.sailOutput.toList)
  IO.FS.writeFile (out / "console.repr.txt") (reprStr c.state.sailOutput ++ "\n")
  -- These decimal fields are parsed and validated by the host wrapper.
  IO.FS.writeFile (out / "cut.tsv")
    (s!"{target}\t{c.steps}\t{c.tick}\t{c.state.cycleCount}\t{defined}\t{c.state.mem.size}\t{count}\n")
'''


def generate(lua_root: Path) -> str:
    defs = lua_root / "riscv-lean/Lean_RV64D_executable/LeanRV64DExecutable/Defs.lean"
    raw = defs.read_bytes()
    part = raw.decode().split("inductive Register : Type where", 1)[1].split("  deriving", 1)[0]
    registers = re.findall(r"^  \| (\w+)\s*$", part, re.M)
    if not registers or len(registers) != len(set(registers)):
        raise ValueError("could not enumerate Sail's Register constructors")
    out = ["import Vsa.Elf", "", "/-! GENERATED by scripts/gen_capture_cut.py.",
           "Native observation only, not a startup execution certificate.",
           "Register enumeration adapted from ship-your-ocaml's gen_boot_dump.py.",
           f"Sail Defs.lean SHA256: {hashlib.sha256(raw).hexdigest()}. -/", "",
           "open LeanRV64DExecutable Sail ConcurrencyInterfaceV1", "",
           "abbrev CapturedState := SequentialState RegisterType trivialChoiceSource", "",
           "def dumpRegister (σ : CapturedState) (r : Register) : String :=", "  match r with"]
    for r in registers:
        out.extend([f"  | .{r} => match σ.regs.get? .{r} with", '    | none => ""',
                    f'    | some v => "⟨Register.{r}, " ++ reprStr v ++ "⟩,"'])
    out.extend(["", "def allRegisters : List Register := [" +
                ", ".join("." + r for r in registers) + "]", BODY])
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lua-root", type=Path, default=Path.home() / "Documents/code/ship-your-lua")
    ap.add_argument("--out", type=Path, required=True)
    options = ap.parse_args()
    options.out.parent.mkdir(parents=True, exist_ok=True)
    options.out.write_text(generate(options.lua_root))
