#!/bin/bash
# Usage: scripts/gen_prog_clight.sh <Name>            write Tcc/Prog/<Name>/Clight.lean
#        scripts/gen_prog_clight.sh --check [<Name>]  verify (all programs by default)
#
# Phase 3 programs live in c/tests/p3/<name>.c, <name> = <Name> lowercased.
# c/tests/p3/<name>.clight.lean is clightgen's output for it, made by
#   scripts/run_lean_clight.sh --keep --lean c/tests/p3/<name>.clight.lean c/tests/p3/<name>.c
# (clightgen -lean -normalize -fprintf-builtin $CERTORA_CFLAGS). The Lean-side
# copy Tcc/Prog/<Name>/Clight.lean is that file with three mechanical edits:
#   * a "generated" header line;
#   * namespace Prog -> Tcc.Prog.<Name> (clightgen names it after the basename,
#     always prog.c in run_lean_clight.sh);
#   * Info.source_file (a temp path) -> "c/tests/p3/<name>.c".
# --check fails if a Lean copy differs from that, or (when clightgen is built,
# scripts/certora_env.sh) if c/tests/p3/<name>.clight.lean differs from a fresh
# clightgen run in anything but the source_file line.
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)

gen() {  # gen <Name> : the Lean copy on stdout
  local name=$1 lower src
  lower=$(echo "$name" | tr '[:upper:]' '[:lower:]')
  src="$here/c/tests/p3/$lower.clight.lean"
  [ -f "$src" ] || { echo "gen_prog_clight.sh: missing $src" >&2; return 1; }
  echo "-- GENERATED by scripts/gen_prog_clight.sh from c/tests/p3/$lower.clight.lean (clightgen -lean output for c/tests/p3/$lower.c). Do not edit."
  sed -e "s|^namespace Prog\$|namespace Tcc.Prog.$name|" \
      -e "s|^end Prog\$|end Tcc.Prog.$name|" \
      -e "s|^  def source_file : String := \".*\"\$|  def source_file : String := \"c/tests/p3/$lower.c\"|" "$src"
}

strip_source() { grep -v '^  def source_file : String := ' "$1"; }

check_one() {  # check_one <Name>
  local name=$1 lower tmp rc=0
  lower=$(echo "$name" | tr '[:upper:]' '[:lower:]')
  if ! gen "$name" | cmp -s - "$here/Tcc/Prog/$name/Clight.lean"; then
    echo "gen_prog_clight.sh: Tcc/Prog/$name/Clight.lean is not generated from c/tests/p3/$lower.clight.lean" >&2
    rc=1
  fi
  # shellcheck source=/dev/null
  . "$here/scripts/certora_env.sh"
  if [ -x "$CLIGHTGEN" ]; then
    tmp=$(mktemp -d "${TMPDIR:-/tmp}/genclight.XXXXXX")
    cp "$here/c/tests/p3/$lower.c" "$tmp/prog.c"
    # shellcheck disable=SC2086
    "$CLIGHTGEN" -lean -normalize -fprintf-builtin $CERTORA_CFLAGS -I"$here/c/tests/p3" \
      -o "$tmp/Prog.lean" "$tmp/prog.c"
    if ! diff <(strip_source "$tmp/Prog.lean") <(strip_source "$here/c/tests/p3/$lower.clight.lean") >&2; then
      echo "gen_prog_clight.sh: c/tests/p3/$lower.clight.lean is not clightgen's output for c/tests/p3/$lower.c" >&2
      rc=1
    fi
    rm -rf "$tmp"
  else
    echo "  (clightgen not built: c/tests/p3/$lower.clight.lean not re-derived)"
  fi
  return $rc
}

if [ "${1:-}" = "--check" ]; then
  shift
  names=("$@")
  if [ ${#names[@]} -eq 0 ]; then
    for d in "$here"/Tcc/Prog/*/Clight.lean; do
      [ -f "$d" ] && names+=("$(basename "$(dirname "$d")")")
    done
  fi
  rc=0
  for n in "${names[@]}"; do check_one "$n" || rc=1; done
  exit $rc
fi
name=${1:?usage: $0 <Name> | --check [<Name>]}
mkdir -p "$here/Tcc/Prog/$name"
gen "$name" > "$here/Tcc/Prog/$name/Clight.lean"
