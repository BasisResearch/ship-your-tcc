#!/usr/bin/env python3
"""Per-member GNU bitfield ownership, execution and initialized-byte layouts."""
import argparse
import tempfile
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'c/tests/bitfield-attributes'
PLACEMENTS = {'prewidth-aligned', 'comma-leading', 'unnamed-leading', 'mixed-comma-leading'}
# Each case owns its entire declaration. A sibling's attribute must never be
# propagated through the common declaration specifiers.
CASES = {
    'leading-declaration': '__attribute__((aligned(8))) unsigned a:3, b:5, c:2;',
    'leading-specifier': 'unsigned __attribute__((aligned(8))) a:3, b:5, c:2;',
    'leading-unnamed': '__attribute__((aligned(8))) unsigned :3, a:3, b:5, c:2;',
    'trailing-packed': 'unsigned a:31, b:31 __attribute__((packed)), c:2;',
    'trailing-aligned': 'char head; unsigned a:3 __attribute__((aligned(8))), b:5, c:2;',
    'middle-aligned': 'unsigned a:3, b:5 __attribute__((aligned(8))), c:2;',
    'last-aligned': 'unsigned a:3, b:5, c:2 __attribute__((aligned(8)));',
    'prewidth-aligned': 'unsigned a __attribute__((aligned(8))):3, b:5, c:2;',
    'comma-leading': 'unsigned a:3, __attribute__((aligned(8))) b:5, c:2;',
    'unnamed-trailing': 'unsigned a:3, :5 __attribute__((aligned(8))), b:5, c:2;',
    'unnamed-packed': 'unsigned a:3, :30 __attribute__((packed)), b:5, c:2;',
    'unnamed-leading': 'unsigned a:3, __attribute__((aligned(8))) :5, b:5, c:2;',
    'zero-aligned': 'unsigned a:3, :0 __attribute__((aligned(8))), b:5, c:2;',
    'zero-packed': 'unsigned a:3, :0 __attribute__((packed)), b:5, c:2;',
    'mixed-ordinary': 'unsigned a:3, ordinary __attribute__((aligned(8))), b:5, c:2;',
    'mixed-comma-leading': 'unsigned a:3, __attribute__((aligned(8))) ordinary, b:5, c:2;',
    'packed-aligned': 'unsigned a:3, b:5 __attribute__((packed, aligned(8))), c:2;',
    'repeat-attributes': 'unsigned a:3, b:5 __attribute__((packed)) __attribute__((aligned(8))), c:2;',
    'volatile': 'volatile unsigned a:3, b:5 __attribute__((aligned(8))), c:2;',
    'signed': 'signed a:3, b:5 __attribute__((aligned(8))), c:2;',
    'nested': 'char head; struct { unsigned a:3, b:5 __attribute__((aligned(8))), c:2; } inner;',
    'anonymous': 'char head; struct { unsigned a:3, b:5 __attribute__((aligned(8))), c:2; };',
    'union': 'unsigned a:3, b:5 __attribute__((aligned(8))), c:2;',
    'aggregate-packed': 'unsigned a:3, b:5 __attribute__((aligned(8))), c:2;',
    'aggregate-aligned': 'unsigned a:3, b:5 __attribute__((packed)), c:2;',
}


def generate():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    batch = ['/* Generated by scripts/gen_bitfield_attribute_fixtures.py. */',
             '#include <stdio.h>', '#include <stddef.h>']
    for name, members in CASES.items():
        union = name == 'union'
        kind = 'union' if union else 'struct'
        attr = (' __attribute__((packed))' if name == 'aggregate-packed' else
                ' __attribute__((aligned(16)))' if name == 'aggregate-aligned' else '')
        decl = f'{kind}{attr} S {{ {members} unsigned char tail; }};'
        path = 'inner.' if name == 'nested' else ''
        values = (('a', '-2'), ('b', '-3'), ('c', '-1')) if name == 'signed' else (('a', '5'), ('b', '19'), ('c', '2'))
        if name == 'trailing-packed':
            values = (('a', '12345'), ('b', '67890'), ('c', '2'))
        if union:
            values = (('b', '19'),)
        assignments = ' '.join(f's.{path}{f}={v};' for f, v in values)
        checks = ' || '.join(f's.{path}{f}!=({v})' for f, v in values)
        if union:
            tail = ''
        else:
            tail = 's.tail=71;'
            checks += ' || s.tail!=71'
        for storage in ('auto', 'static'):
            key = name + '-' + storage
            body = (f'{"static " if storage == "static" else ""}{kind} S s; '
                    'unsigned char *p=(unsigned char *)&s; unsigned i; '
                    'for(i=0;i<sizeof s;++i) p[i]=0; ' + assignments + tail)
            src = '#include <stddef.h>\n' + decl + f'\nint main(void) {{ {body} return {checks}; }}\n'
            file = OUT / (key + '.c')
            file.write_text(src)
            rows.append(dict(name=key, path='c/tests/bitfield-attributes/' + file.name, sha256=hashlib.sha256(src.encode()).hexdigest(), kind='placement-diagnostic' if name in PLACEMENTS else 'defined'))
            if name in PLACEMENTS:
                continue
            # All bytes are initialized by character writes before field stores.
            # Report size/alignment/tail offset and the complete representation.
            layout_body = (body + ' ' + f'printf("{key} %lu %lu %lu", (unsigned long)sizeof s, '
                           f'(unsigned long)_Alignof({kind} S), (unsigned long)offsetof({kind} S,tail)); '
                           'for(i=0;i<sizeof s;++i) printf(" %02x",(unsigned)p[i]); '
                           f'printf("\\n"); return {checks};')
            batch.append(f'static int probe_{key.replace("-", "_")}(void) {{ {decl} {layout_body} }}')
            layout_source = '#include <stdio.h>\n#include <stddef.h>\n' + decl + f'\nint main(void) {{ {layout_body} }}\n'
            layout_file = OUT / ('layout-' + key + '.c')
            layout_file.write_text(layout_source)
            rows[-1].update(layout_path='c/tests/bitfield-attributes/' + layout_file.name,
                            layout_sha256=hashlib.sha256(layout_source.encode()).hexdigest())
    batch.append('int main(void) { int r=0;')
    batch.extend('r += probe_' + r['name'].replace('-', '_') + '();' for r in rows if r['kind'] == 'defined')
    batch.append('return r; }')
    (OUT / 'batch.c').write_text('\n'.join(batch) + '\n')
    (OUT / 'manifest.json').write_text(json.dumps(rows, indent=2) + '\n')
    return rows


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--check', action='store_true'); args = ap.parse_args()
    if not args.check:
        print('generated', len(generate()), 'per-member GNU controls')
    else:
        original = OUT
        with tempfile.TemporaryDirectory() as td:
            OUT = Path(td); generate()
            assert {p.name:p.read_bytes() for p in OUT.iterdir()} == {p.name:p.read_bytes() for p in original.iterdir()}, 'bitfield attribute fixture drift'
        print('bitfield attribute fixtures match generator')
