#!/usr/bin/env python3
"""Focused C11 IEEE comparison; no native engine is part of the semantics.
--batch generates an inline Sail batch; --focused records fresh Lean results.
The retained Sail stdout/meta are checked by --compare-sail, never inferred
from a timeout or a refusal. Pure library vector commands are in the report.
"""
from pathlib import Path
import argparse, hashlib, json, os, re, subprocess, sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'scripts'))
import cfg_probes as cfg
NAMES=['formats','bytes','rounding','nan-bytes','printf']

def batch(dest):
    lines=['/* Generated by scripts/ieee_check.py --batch. */']
    for i,name in enumerate(NAMES):
        lines += [f'#define main ieee_{i}',(ROOT/'csem/tests/ieee'/f'{name}.c').read_text(),'#undef main']
    lines+=['int main(void) { int r;']
    for i,name in enumerate(NAMES):
        lines += [f'r=ieee_{i}(); printf("{name}=%d\\n",r); if(r) return {i+1};']
    lines+=['return 0; }']
    dest.write_text('\n'.join(lines)+'\n')

def focused(dest):
    dest.mkdir(parents=True,exist_ok=True);rows=[]
    for name in NAMES+['nan-conversions','literal-rounding','nonfinite-int-ub']:
        src=ROOT/'csem/tests/ieee'/f'{name}.c'
        cmd=[str(ROOT/'scripts/csem_run.sh')]+(['--libc'] if name in ['printf','literal-rounding'] else [])+['--first','--impl','tcc-rv64',str(src)]
        p=subprocess.run(cmd,capture_output=True,timeout=180)
        (dest/(name+'.out')).write_bytes(p.stdout);(dest/(name+'.err')).write_bytes(p.stderr)
        text=p.stdout.decode()
        m=cfg.DEFINED.fullmatch(text.strip())
        defined=bool(m and p.returncode==0 and int(m[1])==0)
        ub=name=='nonfinite-int-ub' and p.returncode==1 and text.startswith('Undefined {ub: "UB017_out_of_range_floating_integer_conversion"')
        rows.append(dict(name=name,command=cmd,exit=p.returncode,source_sha256=hashlib.sha256(src.read_bytes()).hexdigest(),status='DEFINED_ZERO' if defined else 'UB017' if ub else 'FAIL'))
        print(name,rows[-1]['status'],flush=True)
    (dest/'results.json').write_text(json.dumps(rows,indent=2)+'\n')
    return all(r['status']!='FAIL' for r in rows)

def compare_sail(dest):
    out=(dest/'sail-focused-inline.out').read_bytes()
    if (dest/'sail-focused-inline.exit').read_text().strip()!='0':raise ValueError('Sail batch did not exit zero')
    meta=(dest/'sail-focused-inline.meta').read_text()
    if not re.search(r'^program_steps=[1-9][0-9]*$',meta,re.M):raise ValueError('missing traced Sail program exit')
    expected=b''
    for name in NAMES:
        if name=='printf':
            m=cfg.DEFINED.fullmatch((dest/'focused/printf.out').read_text().strip())
            if not m:raise ValueError('missing Lean printf verdict')
            expected+=cfg.unescape(m[2]).encode()
        expected+=f'{name}=0\n'.encode()
    if out!=expected:raise ValueError(f'Sail/Lean bytes differ: {out!r} != {expected!r}')
    print('focused Sail/Lean bytes and exit agree')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--batch',type=Path);p.add_argument('--focused',type=Path);p.add_argument('--compare-sail',type=Path)
    a=p.parse_args()
    if a.batch:batch(a.batch)
    if a.focused and not focused(a.focused):sys.exit(1)
    if a.compare_sail:compare_sail(a.compare_sail)
