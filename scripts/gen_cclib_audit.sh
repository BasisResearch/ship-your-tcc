#!/bin/bash
# Usage: scripts/gen_cclib_audit.sh            write Tcc/Audit/StepOrig.lean
#        scripts/gen_cclib_audit.sh --check    verify it is up to date
#
# Tcc/Audit/StepOrig.lean is Certora's ORIGINAL `Clight.step` (the inductive
# `Step` of the pristine vendor/certora-export/CCLib/Clight.lean, before patch
# 0002), with two renames so it can live next to the patched library:
# `Step` -> `StepOrig` and `externalCall` -> `externalCallOrig` (the pristine
# external-call definition, which the patch keeps under that name).
# Tcc/Audit/CertoraInstance.lean proves it equivalent to the patched `Step`,
# i.e. to `StepWith certoraExtEnv`.
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
out="$here/Tcc/Audit/StepOrig.lean"
gen() {
  cat <<'EOF'
-- GENERATED by scripts/gen_cclib_audit.sh from vendor/certora-export/CCLib/Clight.lean
-- (pristine Certora/clean @ vendor/CERTORA_REV): the original `Step`, renamed. Do not edit.
import CCLib

namespace Tcc.Audit
open CC

EOF
  awk '/^\/-- `Clight.step` — 26 rules/{on=1} /^\/-! ## Whole-program semantics -\//{on=0} on' \
    "$here/vendor/certora-export/CCLib/Clight.lean" |
    sed -e 's/\bStep\b/StepOrig/g' -e 's/\bexternalCall\b/externalCallOrig/g'
  printf 'end Tcc.Audit\n'
}
if [ "${1:-}" = "--check" ]; then
  gen | cmp -s - "$out" || { echo "gen_cclib_audit.sh: $out is stale (rerun scripts/gen_cclib_audit.sh)" >&2; exit 1; }
  exit 0
fi
mkdir -p "$(dirname "$out")"
gen > "$out"
