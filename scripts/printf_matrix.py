#!/usr/bin/env python3
"""Differential test of `Tcc.Clight.format` against the image's newlib printf
on the integer subset (the content of PHASES `PrintfSpec_Statement`).

    scripts/printf_matrix.py [--out build/printf-matrix] [--run]

Generates a C program making one printf call per case (formats of the
integer subset: every flag set of `- + space # 0`, widths, precisions, every
length modifier, `d i u x X o c %`, extreme values) and printing each call's
return value, and a Lean program evaluating `Tcc.Clight.format` on the same
cases. With `--run`, runs the C program on Sail under `tcc -run`
(scripts/run_tcc_sail.sh: the relocated newlib in tcc's arena, the code the
spec is about) and compiled by xPack gcc (scripts/run_xgcc_sail.sh: the same
libc.a members linked by GNU ld), and the Lean program (`lake env lean
--run`), and compares,
case by case, the bytes and the return value wherever `format` is defined
(`format` is `none` outside the model, e.g. `%#d`: no claim there).
Writes results/p3/printf-matrix.md.
"""
import argparse
import itertools
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

INT_VALS = [0, 1, -1, 42, -42, 255, 65537, 2147483647, -2147483648]
LONG_VALS = [0, -1, 42, 4294967296, 9223372036854775807, -9223372036854775808]
FLAGS = [''.join(s) for n in range(6) for s in itertools.combinations('-+ #0', n)]


def cases():
    out = []
    # A: every flag set, widths, precisions, on int conversions
    for conv in 'diuxXo':
        for fl in FLAGS:
            for w in ['', '6']:
                for p in ['', '.0', '.3']:
                    for v in [0, 42, -42, -2147483648]:
                        out.append((f'%{fl}{w}{p}{conv}', 'int', v))
    # B: every length modifier
    for conv in 'diuxo':
        for ln in ['', 'hh', 'h', 'l', 'll', 'z', 'j', 't']:
            for fl in ['', '#', '+', '-', '0']:
                for w in ['', '25']:
                    vals = LONG_VALS if ln in ('l', 'll', 'z', 'j', 't') else INT_VALS
                    for v in vals:
                        out.append((f'%{fl}{w}{ln}{conv}', 'long' if ln in ('l', 'll', 'z', 'j', 't') else 'int', v))
    # C: %c and %%
    for fl in ['', '-']:
        for w in ['', '3']:
            for v in [65, 33, 126]:
                out.append((f'%{fl}{w}c', 'int', v))
    out.append(('%%', 'none', 0))
    out.append(('a%%b', 'none', 0))
    # D: text around a conversion
    for v in INT_VALS:
        out.append(('x=%d, y', 'int', v))
        out.append(('[%08.3x]', 'int', v))
    return out


def c_lit(f):
    return '"' + f + '"'


def gen_c(cs):
    lines = ['/* GENERATED by scripts/printf_matrix.py: one printf per case, then its',
             ' * return value after \\001. */',
             'int printf(const char *fmt, ...);', 'int main(void) {', '  int r;']
    for f, ty, v in cs:
        if ty == 'none':
            call = f'printf({c_lit(f)})'
        elif ty == 'int':
            call = f'printf({c_lit(f)}, (int)({v}))' if v != -2147483648 \
                else f'printf({c_lit(f)}, (int)(-2147483647 - 1))'
        else:
            call = f'printf({c_lit(f)}, (long){v}L)' if v != -9223372036854775808 \
                else f'printf({c_lit(f)}, (long)(-9223372036854775807L - 1))'
        lines.append(f'  r = {call}; printf("\\001%d\\n", r);')
    lines += ['  return 0;', '}']
    return '\n'.join(lines) + '\n'


def lean_arg(ty, v):
    if ty == 'none':
        return '[]'
    if ty == 'int':
        return f'[.EVint (Integers.Int.repr ({v}))]'
    return f'[.EVlong (Integers.Int64.repr ({v}))]'


def gen_lean(cs):
    # list literals in blocks of 100 (a long literal exceeds the elaborator's depth)
    blocks = [cs[i:i + 100] for i in range(0, len(cs), 100)]
    defs = []
    for b, blk in enumerate(blocks):
        rows = ',\n  '.join(f'({c_lit(f)}, {lean_arg(ty, v)})' for f, ty, v in blk)
        defs.append(f'def cases{b} : List (String × List EventVal) := [\n  {rows}]')
    allc = ' ++ '.join(f'cases{b}' for b in range(len(blocks)))
    nl = '\n\n'
    return f'''-- GENERATED by scripts/printf_matrix.py
import Tcc.Clight.Printf
open CC Tcc.Clight

{nl.join(defs)}

def main : IO Unit := do
  for (f, a) in {allc} do
    match format (fun _ _ => none) f.toUTF8.toList a with
    | some o => IO.println s!"{{String.fromUTF8! (ByteArray.mk o.toArray)}}\x01{{o.length}}"
    | none => IO.println "\x02NONE"
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(ROOT / 'build/printf-matrix'))
    ap.add_argument('--run', action='store_true')
    ap.add_argument('--oracles', default='xgcc,tcc',
                    help='which Sail oracles to run (tcc: about 2 hours for this matrix)')
    ap.add_argument('--compare', action='store_true',
                    help='only compare existing tcc.out and lean.out in --out')
    a = ap.parse_args()
    if a.compare:
        compare(cases(), Path(a.out))
        return
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    cs = cases()
    (out / 'matrix.c').write_text(gen_c(cs))
    (out / 'Matrix.lean').write_text(gen_lean(cs))
    print(f'printf_matrix: {len(cs)} cases in {out}')
    if not a.run:
        return
    for name in a.oracles.split(','):
        meta = out / f'{name}.meta'
        meta.unlink(missing_ok=True)
        env = dict(os.environ, MAX_STEPS='2000000000', ORACLE_META=str(meta))
        with open(out / f'{name}.out', 'wb') as fo, open(out / f'{name}.err', 'wb') as fe:
            rc = subprocess.run([str(ROOT / f'scripts/run_{name}_sail.sh'), str(out / 'matrix.c')],
                                stdout=fo, stderr=fe, env=env).returncode
        with open(meta, 'a') as fm:
            fm.write(f'rc={rc}\n')
    with open(out / 'lean.out', 'wb') as fo:
        subprocess.run(['lake', 'env', 'lean', '--run', str(out / 'Matrix.lean')], stdout=fo,
                       check=True, cwd=ROOT)
    compare(cs, out)


ORACLES = [('tcc', '`tcc -run` on Sail: the relocated newlib in tcc\'s arena (the code the spec is about)'),
           ('xgcc', 'xPack gcc -O0 rv64i on Sail: the same libc.a members, linked by GNU ld')]


def compare(cs, out, rc=None):
    lean = (out / 'lean.out').read_bytes().split(b'\n')
    undefined = sum(1 for k in range(len(cs)) if lean[k].startswith(b'\x02NONE'))
    lines = ['# printf matrix: `Tcc.Clight.format` against newlib (integer subset)', '',
             'GENERATED by `scripts/printf_matrix.py`: one `printf` per case, each compared,',
             'bytes and return value, with `Tcc.Clight.format` (the output `PrintfSpec_Statement`',
             'claims) wherever `format` is defined.', '',
             f'* cases: {len(cs)}; `format` defined on {len(cs) - undefined}, undefined (no claim) on {undefined}']
    bad_all = []
    for name, what in ORACLES:
        f_out, f_meta = out / f'{name}.out', out / f'{name}.meta'
        if not f_meta.exists() or 'rc=' not in f_meta.read_text():
            lines.append(f'* {what}: not run')
            continue
        got_l = f_out.read_bytes().split(b'\n')
        agree, bad = 0, []
        for k, (f, ty, v) in enumerate(cs):
            exp = lean[k]
            if exp.startswith(b'\x02NONE'):
                continue
            got = got_l[k] if k < len(got_l) else b'<missing>'
            if got == exp:
                agree += 1
            else:
                bad.append((name, f, ty, v, got, exp))
        meta = ' '.join(f_meta.read_text().split())
        lines.append(f'* {what}: agree {agree}, disagree {len(bad)} ({meta})')
        bad_all += bad
    lines.append('')
    if bad_all:
        lines.append('| oracle | format | type | value | newlib | format |')
        lines.append('|---|---|---|---|---|---|')
        for name, f, ty, v, got, exp in bad_all[:200]:
            lines.append(f'| {name} | `{f}` | {ty} | {v} | `{got!r}` | `{exp!r}` |')
    (ROOT / 'results/p3/printf-matrix.md').write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
