#!/usr/bin/env python3
"""Direct IEEE source-literal vectors, independent of compilers/model data.

Reuse the binary128 suite's exact rational oracle. Hex strings preserve every
dyadic digit; decimal boundary brackets are themselves exact rationals.
"""
import argparse
from fractions import Fraction as F
from pathlib import Path
import sys

from gen_ld_literal_tests import decimal, pow2, round_bits

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'c/tests/model/float_direct.c'
SAIL_OUT = ROOT / 'c/tests/model/float_direct_sail.c'
FORMATS = [('float', 'f', 23, 8), ('double', '', 52, 11),
           ('long double', 'L', 112, 15)]


def hex_text(x):
    n, d = x.numerator, x.denominator
    k = d.bit_length() - 1
    assert d == 1 << k
    if n:
        shift = (n & -n).bit_length() - 1
        n >>= shift
        k -= shift
    return f'0x{n:x}p{-k:+d}'


def vectors(fraction, ebits, stress=False):
    bias = 2 ** (ebits - 1) - 1
    quantum = 1 - bias - fraction
    vals = [('zero', F(0)), ('one', F(1)), ('one and half', F(3, 2))]
    # Long tails extend beyond binary128 precision and the inherited bn[4].
    for name, mid in [('even', 1 + pow2(-fraction-1)),
                      ('odd', 1 + 3 * pow2(-fraction-1)),
                      ('carry', 2 - pow2(-fraction-1))]:
        for side in [-1, 0, 1]:
            vals.append((f'{name} tie {side}', mid + side * pow2(-220)))
    vals += [('half min subnormal', pow2(quantum-1)),
             ('above half min subnormal', pow2(quantum-1) + pow2(quantum-220)),
             ('below half min subnormal', pow2(quantum-1) - pow2(quantum-220)),
             ('odd subnormal tie', 3 * pow2(quantum-1)),
             ('min subnormal', pow2(quantum)),
             ('normal boundary tie', pow2(1-bias) - pow2(quantum-1)),
             ('min normal', pow2(1-bias)),
             ('max finite', (2-pow2(-fraction)) * pow2(bias)),
             ('overflow tie', (2-pow2(-fraction-1)) * pow2(bias))]
    cases = []
    for name, x in vals:
        cases.append((name + ' hex', hex_text(x), round_bits(x, fraction, ebits)))
        # Exact near-one ties; bounded significant digits at extreme exponents.
        if not x or F(1, 2) <= x <= 2:
            txt = decimal(x, exact=True)
            cases.append((name + ' decimal', txt, round_bits(F(txt), fraction, ebits)))
        else:
            for side in [-1, 1]:
                txt = decimal(x, direction=side)
                cases.append((name + f' decimal bracket {side}', txt,
                              round_bits(F(txt), fraction, ebits)))
    cases += [('long leading zeros', '0000000000.00000000125e9',
               round_bits(F(5, 4), fraction, ebits)),
              ('uppercase hex', '0X1.ABCP+4', round_bits(F(0x1abc, 256), fraction, ebits)),
              ('huge exponent', '1e999999999', (2**ebits-1) << fraction),
              ('tiny exponent', '1e-999999999', 0),
              ('huge hex exponent', '0x1p999999999', (2**ebits-1) << fraction),
              ('tiny hex exponent', '0x1p-999999999', 0)]
    if stress:
        import random
        rng = random.Random(20261027 + fraction)
        for i in range(100):
            x = F(rng.randrange(1, 2**240)) * pow2(rng.randrange(quantum-250, bias-239))
            for txt in [hex_text(x), decimal(x)]:
                value = x if txt.startswith('0x') else F(txt)
                cases.append((f'random {i}', txt, round_bits(value, fraction, ebits)))
    return cases + [(name + ' negative', '-' + txt, value | (1 << (fraction+ebits)))
                    for name, txt, value in cases[:2] + cases[-4:]]


def render(stress=False, focused=False):
    out = ['/* Generated by scripts/gen_float_literal_tests.py; edit the generator. */',
           '/* Exact rational expected bytes; no compiler, model or native Float oracle. */',
           '#include <stdio.h>']
    total = 0
    for idx, (ty, suffix, frac, exp) in enumerate(FORMATS):
        count = (frac + exp + 1) // 8
        cases = vectors(frac, exp, stress)
        if focused:
            names = {'even tie 1 hex', 'odd tie 0 hex', 'half min subnormal hex',
                     'overflow tie hex', 'even tie 1 decimal'}
            cases = [c for c in cases if c[0] in names]
            assert len(cases) == 5
        total += len(cases)
        out.append(f'static const struct {{ {ty} value; unsigned char expected[{count}]; }} v{idx}[] = {{')
        for name, txt, value in cases:
            assert len(txt) < 1024
            bs = ','.join(str(b) for b in value.to_bytes(count, 'little'))
            out.append(f'  {{ {txt}{suffix}, {{ {bs} }} }}, /* {name} */')
        out.append('};')
    out += ['int main(void) {', '  unsigned i, j, bad = 0;']
    for idx, (_, _, frac, exp) in enumerate(FORMATS):
        count = (frac + exp + 1) // 8
        out += [f'  for (i = 0; i < sizeof v{idx}/sizeof v{idx}[0]; ++i) {{',
                f'    const unsigned char *p = (const unsigned char *)&v{idx}[i].value;',
                f'    for (j = 0; j < {count}; ++j) if (p[j] != v{idx}[i].expected[j]) {{',
                f'      printf("format {frac+exp+1} case %u byte %u: %u expected %u\\n", i, j, p[j], v{idx}[i].expected[j]);',
                '      ++bad; break;', '    }', '  }']
    out += [f'  printf("direct literals %u/{total}\\n", {total}-bad);',
            '  return bad != 0;', '}', '']
    return '\n'.join(out)


if __name__ == '__main__':
    sys.set_int_max_str_digits(20000)
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--stress-out', type=Path)
    args = ap.parse_args()
    content = render(stress=bool(args.stress_out))
    if args.check:
        assert OUT.read_text() == content, 'regenerate float_direct.c'
        assert SAIL_OUT.read_text() == render(focused=True), 'regenerate float_direct_sail.c'
    else:
        (args.stress_out or OUT).write_text(content)
        if not args.stress_out:
            SAIL_OUT.write_text(render(focused=True))
