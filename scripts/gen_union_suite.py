#!/usr/bin/env python3
"""One C11 translation unit for all positive union fixtures (one Sail boot).
Rename every non-keyword identifier per fixture while preserving literals and
comments; the fixtures deliberately use no external library declarations.
"""
from pathlib import Path
import argparse
import json
import re
ROOT=Path(__file__).resolve().parents[1]
F=ROOT/'csem/tests/union-init'
KEYWORDS=set('auto break case char const continue default do double else enum extern float for goto if inline int long register restrict return short signed sizeof static struct switch typedef union unsigned void volatile while _Alignas _Alignof _Atomic _Bool _Complex _Generic _Imaginary _Noreturn _Static_assert _Thread_local'.split())
TOKEN=re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|\b[A-Za-z_]\w*')
def generate():
    expected=json.loads((F/'expected.json').read_text())
    # This inherited control violates C11 6.7.9p2 (excess initializers).
    # Keep its old GCC/CSem check, but tcc may correctly reject it. It is not
    # a conforming C11 case and does not belong in a successful Sail run.
    del expected['ctl_in_struct_positional']
    parts=['/* Generated by scripts/gen_union_suite.py; 33 conforming C11 observations. */\n']
    for i,(name,value) in enumerate(expected.items()):
        s=(F/(name+'.c')).read_text()
        assert '#' not in s, f'fixture must be self-contained without preprocessing: {name}'
        def rename(m):
            t=m[0]
            return f'u{i}_{t}' if re.fullmatch(r'[A-Za-z_]\w*',t) and t not in KEYWORDS else t
        parts.append(f'/* case {i+1}: {name}, expected {value} */\n'+TOKEN.sub(rename,s)+'\n')
    parts.append('int main(void) {\n')
    for i,(name,value) in enumerate(expected.items()):
        parts.append(f'  if (u{i}_main() != {value}) return {i+1}; /* {name} */\n')
    parts.append('  return 0;\n}\n')
    return ''.join(parts)
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
out=ROOT/'csem/tests/union-init-batch.c';s=generate()
if a.check:
    assert out.read_text()==s, 'stale union suite batch'
else:
    out.write_text(s)
