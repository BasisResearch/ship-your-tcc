#!/bin/sh
# ship-your-tcc: copied from ship-your-ocaml c/src/gen_embed.sh (commit
# 272e4361) and adapted for tcc -run:
# - the command line is { "tcc", args..., "-run", "/prog.c", NULL } (was
#   { "ocamlrun", "/prog", args... }); there is no OCAMLRUNPARAM, the
#   environment is empty;
# - a fourth header word, `embedded_flags` (main.c: bit 0 dumps the
#   generated code to the console before the jump into it);
# - `--list FILE` reads more `/path/in/image=host/file` specs, one per line
#   (the header tree has ~150 files).
#
# Emit embed.S: everything that varies with the embedded program, in the
# `.embed` section at a FIXED address (src/link.ld), so the runtime's code
# and data are byte-identical whatever program is embedded:
#   gen_embed.sh [--cargs '"a","b",'] [--flags N] [--list F] /path/in/image=host/file ...
# The section starts with a fixed four-word header (so the code's
# addresses do not depend on how many files or arguments follow):
# * `embedded_files`: -> {path, start, end} triples, NULL-terminated (htif.c);
# * `embedded_argv`: -> { "tcc", args..., "-run", "/prog.c", NULL } (main.c);
# * `embedded_env`: -> { NULL } (main.c);
# * `embedded_flags`: a word (main.c).
set -e
cargs=; flags=0; list=
while :; do
  case "$1" in
    --cargs) cargs=$2; shift 2 ;;
    --flags) flags=$2; shift 2 ;;
    --list) list=$2; shift 2 ;;
    *) break ;;
  esac
done
specs=$(mktemp)
trap 'rm -f "$specs"' EXIT
for spec in "$@"; do echo "$spec"; done > "$specs"
[ -n "$list" ] && grep -v '^[[:space:]]*$' "$list" >> "$specs"
echo '/* Generated by gen_embed.sh: the embedded program, its files and command line (see main.c, htif.c). */'
echo '    .section .embed,"aw"'
echo '    .balign 8'
echo '    .globl embedded_files, embedded_argv, embedded_env, embedded_flags'
echo 'embedded_files: .dword _files_table'
echo 'embedded_argv: .dword _argv_table'
echo 'embedded_env: .dword _env_table'
echo "embedded_flags: .dword $flags"
echo '_files_table:'
i=0
while IFS= read -r spec; do
  echo "    .dword _file${i}_path, _file${i}_start, _file${i}_end"
  i=$((i+1))
done < "$specs"
echo '    .dword 0, 0, 0'
# one argument per line, quotes kept (they are asm string literals)
args=$(printf '%s' "$cargs" | grep -o '"[^"]*"' || true)
echo '_argv_table:'
echo '    .dword _arg_tcc'
n=0
for a in $args; do echo "    .dword _arg${n}"; n=$((n+1)); done
echo '    .dword _arg_run, _arg_prog, 0'
echo '_env_table:'
echo '    .dword 0'
echo '_arg_tcc: .asciz "tcc"'
n=0
for a in $args; do echo "_arg${n}: .asciz $a"; n=$((n+1)); done
echo '_arg_run: .asciz "-run"'
echo '_arg_prog: .asciz "/prog.c"'
i=0
while IFS= read -r spec; do
  path=${spec%%=*}; file=${spec#*=}
  [ -f "$file" ] || { echo "gen_embed.sh: no such file: $file" >&2; exit 1; }
  echo "    .balign 8"
  echo "_file${i}_start:"
  echo "    .incbin \"$file\""
  echo "_file${i}_end:"
  echo "    .byte 0"
  echo "_file${i}_path:"
  echo "    .asciz \"$path\""
  i=$((i+1))
done < "$specs"
